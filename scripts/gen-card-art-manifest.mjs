#!/usr/bin/env node
/**
 * Scan public/cards/players/ for per-player images and write the manifest
 * (src/game/cardArt.js) that maps card id → filename. Run this after dropping
 * generated images in, so the app displays them without probing for files
 * that don't exist.
 *
 *   node scripts/gen-card-art-manifest.mjs
 *
 * Accepts .png/.webp/.jpg/.jpeg named by card id (e.g. wc26-49673.png).
 */
import { readdirSync, writeFileSync, existsSync } from 'node:fs';

const DIR = 'public/cards/players';
const files = existsSync(DIR) ? readdirSync(DIR).filter((f) => /\.(png|webp|jpe?g)$/i.test(f)) : [];

const entries = files
  .map((f) => [f.replace(/\.(png|webp|jpe?g)$/i, ''), f])
  .sort((a, b) => a[0].localeCompare(b[0]));

const body =
  '// GENERATED by scripts/gen-card-art-manifest.mjs — do not edit by hand.\n' +
  '// Maps a card id to its per-player image filename in public/cards/players/.\n' +
  '// Cards without an entry fall back to the shared position archetype art.\n' +
  'export const CARD_ART = new Map([\n' +
  entries.map(([id, file]) => `  [${JSON.stringify(id)}, ${JSON.stringify(file)}],`).join('\n') +
  (entries.length ? '\n' : '') +
  ']);\n';

writeFileSync('src/game/cardArt.js', body);
console.error(`manifest: ${entries.length} per-player images mapped in ${DIR}`);
